import assert from 'node:assert/strict'
import { communicationHint, followUpHint } from '../src/communicationPrompt.js'
const example='had a talk with Mohsin Sb, he is saying he will visit on Saturday'
assert.deepEqual(communicationHint(example),{channel:'',contact:'Mohsin Sb'})
for(const text of ['Will call Mohsin on Saturday','Planning a meeting','Need to discuss this','I did not call him','I never talked to him','We met the deadline','I called the API','We discussed the architecture'])assert.equal(communicationHint(text),null,text)
assert.deepEqual(communicationHint('Called Mohsin, he will visit Saturday'),{channel:'Call',contact:'Mohsin'})
assert.equal(communicationHint('Received an email from Mohsin, he confirmed').contact,'Mohsin')
assert.equal(communicationHint('Emailed the customer').channel,'Email')
assert.equal(communicationHint('Had a talk with Mohsin; will email the customer').channel,'')
assert.equal(followUpHint('I spoke with Mohsin on Monday, he will call next week','2026-11-19'),'')
assert.equal(followUpHint(example,'2026-11-19 10:00:00'),'2026-11-21')
assert.equal(followUpHint('Will visit next Saturday','2026-11-19'),'')
assert.equal(followUpHint('Will visit on Saturday','2026-11-21'),'')
assert.equal(followUpHint('Will visit Monday or Saturday','2026-11-19'),'')
assert.equal(followUpHint('Follow up due 2026-11-25','2026-11-19'),'2026-11-25')
assert.equal(followUpHint('Follow up due 2026-02-30','2026-11-19'),'')
assert.equal(followUpHint('Talked Saturday','2026-11-19'),'')
console.log('communication prompt detection checks passed')

const {createCommunicationDismissals,savedCommunicationPrompts}=await import('../src/communicationPrompt.js')
let data=null
const storage={getItem:()=>data,setItem:(_key,value)=>data=value}
let dismissals=createCommunicationDismissals(()=>storage)
const saved=(name,actor='me',reply_to=null)=>({name,kind:'Comment',actor,reply_to,body:example,recorded_at:'2026-11-19 10:00:00'})
const issue={name:'issue1',status:'Open',timeline:[saved('own'),saved('reply','me','root'),saved('other','someone')]}
const prompts=(user='me',doc=issue,date='2026-11-19')=>savedCommunicationPrompts(doc,user,dismissals,text=>text,date)
assert.deepEqual(Object.keys(prompts('')),[],'wait for identity')
assert.deepEqual(Object.keys(prompts()),['reply','own'],'own saved roots and replies')
assert.equal(prompts().own.followUpDate,'2026-11-21')
assert.equal(prompts('me',issue,'2026-11-22').own.followUpDate,'','elapsed historical date blank')
assert.deepEqual(Object.keys(prompts('me',{...issue,status:'Resolved'})),[])
assert.deepEqual(Object.keys(prompts('me',{...issue,timeline:[...issue.timeline,{kind:'Communication',source_comment:'own'}]})),['reply'],'linked skipped')
dismissals.add('me','issue1','own')
dismissals=createCommunicationDismissals(()=>storage)
assert.deepEqual(Object.keys(prompts()),['reply'],'dismissal survives reload')
assert.equal(dismissals.has('someone','issue1','own'),false,'user scoped')
assert.equal(dismissals.has('me','issue2','own'),false,'issue scoped')
const broken=createCommunicationDismissals(()=>{throw Error('disabled')})
broken.add('me','issue','comment');assert.equal(broken.has('me','issue','comment'),true,'memory fallback')
for(let i=0;i<250;i++)dismissals.add('me','issue1','id'+i)
assert.equal(JSON.parse(data).length,200,'bounded storage')
assert.equal(Object.keys(prompts('me',{...issue,timeline:Array.from({length:10},(_,i)=>saved('new'+i))})).length,10,'older eligible comments remain reviewable')
console.log('saved comment prompts and dismissal checks passed')
